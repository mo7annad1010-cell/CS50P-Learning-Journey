def main():
    print("--- اختبار الحماية بـ try/except ---")

    try:
        # نطلب من المستخدم إدخال رقم ونحاول تحويله إلى عدد صحيح (int)
        number = int(input("أدخل رقماً صحيحاً من فضلك: "))
        print(f"ممتاز! الرقم الذي أدخلته هو: {number}")

    except ValueError:
        # إذا كتب المستخدم حروفاً بدلاً من الأرقام، سيحدث خطأ ValueError
        # وهنا يأتي دور الـ except لإنقاذ الموقف بدلاً من انهيار البرنامج!
        print("خطأ: لقد أدخلت نصاً أو رموزاً، ولم تقم بإدخال رقم صحيح!")

if __name__ == "__main__":
    main()

